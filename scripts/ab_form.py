"""E3 expert blind A/B (memory ablation) and teacher feedback rating, blueprint §4.3 Layer 4.

The same answers are marked twice by the final configuration: student memory OFF and ON (step 4 of
eval/experiments.py). For each sample a teacher sees the pupil's history, the question, the answer and
two feedbacks "A" and "B" (order shuffled, the key is hidden), then
  - picks which feedback fits this pupil better (A / B / sama baik)   -> memory win-rate
  - rates each feedback 1-5 on four aspects                          -> Likert means
    (betul dari segi agama, berkaitan dengan jawapan, jelas untuk murid Tahun 5, cadangan berguna)

  make       .venv\\Scripts\\python scripts\\ab_form.py make <memory-off run> <memory-on run> [--n 10]
             -> data/teacher/ab_form/create_ab_form.gs (paste into script.google.com, run createAbForm)
                data/teacher/ab_form/ab_key.json (which of A/B is memory ON; do not share)
  from-form  .venv\\Scripts\\python scripts\\ab_form.py from-form responses.csv
             -> data/teacher/ab_results.json (read by the evaluation page)
Teachers are told apart by "Nama guru"; any number of teachers can answer.
"""
from __future__ import annotations

import argparse
import csv
import json
import random
import re
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "eval"))

from backend.app.questions import load_questions  # noqa: E402

OUT = ROOT / "data" / "teacher" / "ab_form"
KEY = OUT / "ab_key.json"
RESULTS = ROOT / "data" / "teacher" / "ab_results.json"
EXP = ROOT / "eval" / "results" / "experiments"
ASPECTS = ["Betul dari segi agama", "Berkaitan dengan jawapan murid", "Jelas untuk murid Tahun 5", "Cadangan langkah seterusnya berguna"]
PREF = ["A lebih sesuai", "B lebih sesuai", "Sama baik"]
NAME = "Nama guru"
TITLE = "Perbandingan Maklum Balas KAFA (A/B)"
INTRO = ("Terima kasih kerana membantu. Setiap halaman menunjukkan sejarah seorang murid, soalan, jawapan murid "
         "dan DUA maklum balas (A dan B) daripada sistem. Pilih maklum balas yang lebih sesuai untuk murid ini, "
         "kemudian nilaikan kedua-duanya (1 = sangat tidak setuju, 5 = sangat setuju). "
         "Jawapan dan sejarah murid ialah contoh untuk kajian, bukan murid sebenar. Sila jawab seorang diri.")

GS = """// Creates the blind A/B feedback form. Generated by scripts/ab_form.py make; do not edit.
// Paste into https://script.google.com (New project), Save, choose createAbForm, Run, then open the Execution log.
var TITLE = __TITLE__; var INTRO = __INTRO__; var NAME = __NAME__;
var PREF = __PREF__; var ASPECTS = __ASPECTS__; var ITEMS = __ITEMS__;
function createAbForm() {
  var form = FormApp.create(TITLE);
  form.setDescription(INTRO).setProgressBar(true).setPublishingSummary(false).setAllowResponseEdits(true);
  form.addTextItem().setTitle(NAME).setHelpText('Nama penuh anda (setiap guru menggunakan nama yang berbeza).').setRequired(true);
  ITEMS.forEach(function (it, i) {
    form.addPageBreakItem().setTitle('Sampel ' + (i + 1) + ' daripada ' + ITEMS.length + ' (' + it.id + ')')
        .setHelpText('SEJARAH MURID: ' + it.history + '\\n\\nSOALAN: ' + it.question + '\\n\\nJAWAPAN MURID: ' + it.answer +
                     '\\n\\nMAKLUM BALAS A:\\n' + it.a + '\\n\\nMAKLUM BALAS B:\\n' + it.b);
    form.addMultipleChoiceItem().setTitle(it.id + ' Pilihan: maklum balas mana lebih sesuai untuk murid ini?')
        .setChoiceValues(PREF).setRequired(true);
    ['A', 'B'].forEach(function (v) {
      form.addGridItem().setTitle(it.id + ' Nilai maklum balas ' + v).setRows(ASPECTS)
          .setColumns(['1', '2', '3', '4', '5']).setRequired(true);
    });
  });
  var sheet = SpreadsheetApp.create(TITLE + ' (Respons)');
  form.setDestination(FormApp.DestinationType.SPREADSHEET, sheet.getId());
  Logger.log('Send this link to every teacher: ' + form.getPublishedUrl());
  Logger.log('Responses sheet: ' + sheet.getUrl());
}
"""


def _load(name: str) -> dict:
    p = Path(name)
    if not p.exists():
        hits = [x for x in EXP.glob(f"*{name}*.json") if not x.name.endswith(".grounding.json")]
        if len(hits) != 1:
            sys.exit(f"{len(hits)} experiment files match '{name}'")
        p = hits[0]
    return json.loads(p.read_text(encoding="utf-8"))


def make(off_name: str, on_name: str, n: int, seed: int = 5) -> None:
    from experiments import load_items, simulated_memory  # noqa: E402
    from silver import load_silver  # noqa: E402

    from backend.app.assess.llm_marking import memory_text

    off, on = _load(off_name), _load(on_name)
    if off["memory"] or not on["memory"]:
        sys.exit("give the memory-OFF run first, then the memory-ON run")
    qs = load_questions()
    pool = load_silver("teacher") if on["data"] == "teacher" else load_silver("test")
    items = {it["answer_id"]: it for it in load_items(on["data"], on["n"])}
    off_fb = {r["answer_id"]: r["feedback"] for r in off["items"] if r["rep"] == 0}
    cands = []
    for r in on["items"]:
        if r["rep"] or not r["feedback"] or not off_fb.get(r["answer_id"]) or r["answer_id"] not in items:
            continue
        mem = simulated_memory(items[r["answer_id"]], pool, qs)
        if mem["recent_mistakes"] and r["feedback"].strip() != off_fb[r["answer_id"]].strip():
            cands.append((r, mem))
    rng = random.Random(seed)
    rng.shuffle(cands)
    form_items, key = [], {}
    for i, (r, mem) in enumerate(cands[:n], 1):
        sid = f"P{i:02d}"
        on_is_a = rng.random() < 0.5
        a, b = (r["feedback"], off_fb[r["answer_id"]]) if on_is_a else (off_fb[r["answer_id"]], r["feedback"])
        form_items.append({"id": sid, "history": memory_text(mem), "question": qs[r["question_id"]]["question_rumi"],
                           "answer": r["answer"], "a": a, "b": b})
        key[sid] = {"answer_id": r["answer_id"], "memory_on": "A" if on_is_a else "B"}
    OUT.mkdir(parents=True, exist_ok=True)
    js = lambda v: json.dumps(v, ensure_ascii=False)  # noqa: E731
    script = (GS.replace("__TITLE__", js(TITLE)).replace("__INTRO__", js(INTRO)).replace("__NAME__", js(NAME))
              .replace("__PREF__", js(PREF)).replace("__ASPECTS__", js(ASPECTS))
              .replace("__ITEMS__", json.dumps(form_items, ensure_ascii=False, indent=1)))
    (OUT / "create_ab_form.gs").write_text(script, encoding="utf-8")
    KEY.write_text(json.dumps({"off": off["config"], "on": on["config"], "data": on["data"], "items": key},
                              indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"{len(form_items)} samples -> {OUT / 'create_ab_form.gs'}  (key: {KEY}, keep it private)")


def from_form(path: Path) -> None:
    key = json.loads(KEY.read_text(encoding="utf-8"))
    with path.open(encoding="utf-8-sig") as fh:
        rows = list(csv.DictReader(fh))
    latest = {}
    for r in rows:                     # a teacher's later submission replaces the earlier one
        name = " ".join((r.get(NAME) or "").split())
        if name:
            latest[name.casefold()] = r
    pref_re = re.compile(r"^(P\d{2}) Pilihan")
    grid_re = re.compile(r"^(P\d{2}) Nilai maklum balas ([AB]) \[(.+)\]$")
    wins = losses = ties = 0
    ratings: dict[str, dict[str, list[int]]] = {"on": defaultdict(list), "off": defaultdict(list)}
    for r in latest.values():
        for col, val in r.items():
            if m := pref_re.match(col or ""):
                k = key["items"].get(m[1])
                if not k or not val:
                    continue
                if val.startswith("Sama"):
                    ties += 1
                elif val[0] == k["memory_on"]:
                    wins += 1
                else:
                    losses += 1
            elif m := grid_re.match(col or ""):
                k = key["items"].get(m[1])
                if k and (val or "").strip().isdigit():
                    ratings["on" if m[2] == k["memory_on"] else "off"][m[3]].append(int(val))
    total = wins + losses + ties
    res = {"teachers": len(latest), "comparisons": total, "memory_wins": wins, "memory_losses": losses, "ties": ties,
           "win_rate": round(wins / total, 3) if total else None,
           "win_rate_excl_ties": round(wins / (wins + losses), 3) if wins + losses else None,
           "likert": {v: {a: round(statistics.mean(x), 2) for a, x in d.items()} for v, d in ratings.items()},
           "likert_mean": {v: round(statistics.mean([y for x in d.values() for y in x]), 2) if d else None
                           for v, d in ratings.items()},
           "config_on": key["on"], "config_off": key["off"], "data": key["data"]}
    RESULTS.write_text(json.dumps(res, indent=1, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(res, indent=1, ensure_ascii=False))


